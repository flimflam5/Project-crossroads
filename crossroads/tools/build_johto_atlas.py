#!/usr/bin/env python3
"""Native schematic atlas labels/positions derived from the same regional topology."""
import argparse,json,re
from pathlib import Path
from johto_world_spec import *
R=Path(__file__).resolve().parents[2]
def generate(check=False):
 names=json.loads((R/'data/maps/map_groups.json').read_text())['gMapGroup_CrossroadsOlivine']
 manifest=json.loads((R/'crossroads/johto/manifest.json').read_text());parents={p['name']:p.get('parent') for p in manifest['planned']}
 points={'OlivineCity':('OLIVINE CITY',(4,11),'OL'),'JohtoRoute39':('ROUTE 39',(6,9),''),'JohtoRoute38':('ROUTE 38',(9,6),''),'EcruteakCity':('ECRUTEAK CITY',(12,6),'EC')}
 for n,(label,c,pos,theme) in CITIES.items():
  if n in names:points[n]=(label,pos,{'GoldenrodCity':'GO','VioletCity':'VI','AzaleaTown':'AZ','CherrygroveCity':'CH','NewBarkTown':'NB','MahoganyTown':'MA','BlackthornCity':'BL','CianwoodCity':'CI'}[n])
 for i,(c,pos,theme,size) in ROUTES.items():
  n='JohtoRoute'+str(i)
  if n in names:points[n]=('ROUTE '+str(i),pos,'')
 for n,label,c,theme,size,pos in LANDMARKS:
  if n in names:points[n]=(label,pos,'')
 for n,label,c,count,theme,mouths in DUNGEONS:
  if n+'_1F' in names:
   parent=mouths[0][0]
   if parent in points:
    x,y=points[parent][1];points[n]=(label,(x+1,min(19,y+1)),'')
 keys=list(points);rows=[]
 for n,(label,(x,y),abbr) in points.items():rows.append(dict(name=n,label=label,x=8+x*7,y=14+y*5,abbreviation=abbr))
 def root(n):
  if n in points:return n
  if n in parents and parents[n]:return root(parents[n])
  base=n.rsplit('_',1)[0]
  if base in points:return base
  if n.startswith('Ecruteak'):return 'EcruteakCity'
  if n.startswith('Olivine'):return 'OlivineCity'
  return 'OlivineCity'
 mapping=[keys.index(root(n)) for n in names]
 edges=[]
 for a,d,b in [('OlivineCity','up','JohtoRoute39'),('JohtoRoute39','up','JohtoRoute38'),('JohtoRoute38','right','EcruteakCity')]+EDGES:
  if a in keys and b in keys:edges.append([keys.index(a),keys.index(b)])
 for n,label,c,count,theme,mouths in DUNGEONS:
  if n in keys:
   for parent,x,y,i in mouths:
    if parent in keys:edges.append([keys.index(parent),keys.index(n)])
 s='// Generated by build_johto_atlas.py. Relative Johto geography, no fast travel.\nstatic const struct JohtoAtlasNode sAtlasNodes[] = {\n'
 for row in rows:s+=f'    {{(const u8[])_("{row["label"]}"), (const u8[])_("{row["abbreviation"]}"), {row["x"]}, {row["y"]}}},\n'
 s+='};\nstatic const u8 sMapAtlasNode[] = {'+','.join(map(str,mapping))+'};\nstatic const u8 sAtlasEdges[][2] = {\n'+''.join(f'    {{{a},{b}}},\n' for a,b in edges)+'};\n'
 for path,data in [('src/data/johto_atlas.h',s),('crossroads/johto/atlas.json',json.dumps(dict(nodes=rows,map_nodes=mapping,edges=edges,scope='Field/wall atlas; Fly and Pokenav interfaces retain legacy maps and are not enabled by this pass.'),indent=2)+'\n')]:
  p=R/path
  if check:assert p.read_text()==data,('Regenerate atlas',path)
  elif not p.exists() or p.read_text()!=data:p.write_text(data)
 print('Johto atlas:',len(rows),'labeled nodes, player positions for',len(mapping),'maps')
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');generate(ap.parse_args().check)
